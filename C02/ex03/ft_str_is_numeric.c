int	ft_isnbr(char c)
{
	if (c >= '0' && c <= '9')
		return (1);
	return (0);
}

int	ft_str_is_numeric(char *str)
{
	while (*str)
	{
		if (!ft_isnbr(*str++))
			return (0);
	}
	return (1);
}
