#include "ft_do_op.h"

int	ft_sum(int a, int b)
{
	return (a + b);
}

int	ft_sub(int a, int b)
{
	return (a - b);
}

int	ft_mult(int a, int b)
{
	return (a * b);
}

int	ft_divi(int a, int b)
{
	return (a / b);
}

int	ft_mod(int a, int b)
{
	return (a % b);
}
